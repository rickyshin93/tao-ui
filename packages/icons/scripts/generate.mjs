import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

const root = fileURLToPath(new URL('../', import.meta.url));
const canonical = JSON.parse(await readFile(path.join(root, 'data/icons.json'), 'utf8'));
const manifest = JSON.parse(await readFile(path.join(root, 'data/manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
assert.equal(Object.keys(canonical.icons).length, manifest.count);
assert.equal(manifest.icons.length, manifest.count);
assert.equal(canonical.version, manifest.version);
assert.equal(canonical.viewBox, '0 0 24 24');
assert.equal(canonical.strokeWidth, 1.8);
const generated = new Map();

for (const icon of [...manifest.icons].sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
  assert.match(icon.name, /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/);
  assert.equal(icon.component, icon.name.split('-').map(x => x[0].toUpperCase() + x.slice(1)).join('') + 'Icon');
  const body = canonical.icons[icon.name];
  assert.ok(body, `Missing canonical geometry: ${icon.name}`);
  // Only self-contained geometry is rendered as JSX.
  assert.match(body, /^(?:<(?:path|circle|rect|ellipse)\s[^<>]+\/>)+$/);
  assert.ok(!/\bon\w+=|[{}]|<script|dangerouslySetInnerHTML/.test(body));
  const svg = await readFile(path.join(root, 'svg', `${icon.name}.svg`), 'utf8');
  assert.equal(svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1], body, `${icon.name} SVG geometry drift`);
  const jsx = body.replace(/ (stroke-width|stroke-dasharray|fill-rule)=/g, attribute =>
    attribute.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()),
  );
  generated.set(`src/icons/${icon.name}.tsx`, `// Generated by scripts/generate.mjs.\n'use client';\n\nimport { forwardRef } from 'react';\nimport type { IconProps } from '../types.js';\nimport { resolveIconProps } from '../icon-props.js';\n\nexport const ${icon.component} = /* @__PURE__ */ forwardRef<SVGSVGElement, IconProps>(\n  function ${icon.component}(props, ref) {\n    const { title, titleId, children, svgProps } = resolveIconProps(props);\n    return (\n      <svg {...svgProps} ref={ref}>\n        {title ? <title id={titleId}>{title}</title> : null}\n        ${jsx}\n        {children}\n      </svg>\n    );\n  },\n);\n`);
}
generated.set('src/index.ts', `// Generated by scripts/generate.mjs.\n'use client';\n\nexport type { IconProps } from './types.js';\n${[...manifest.icons].sort((a, b) => a.name.localeCompare(b.name, 'en')).map(i => `export { ${i.component} } from './icons/${i.name}.js';`).join('\n')}\n`);
await mkdir(path.join(root, 'src/icons'), { recursive: true });
for (const name of await readdir(path.join(root, 'src/icons'))) {
  if (!generated.has(`src/icons/${name}`)) {
    if (check) throw new Error(`Unexpected generated file: ${name}`);
    await unlink(path.join(root, 'src/icons', name));
  }
}
for (const [relative, content] of generated) {
  const destination = path.join(root, relative);
  if (check) assert.equal(await readFile(destination, 'utf8'), content, `Stale generated file: ${relative}`);
  else await writeFile(destination, content);
}
console.log(`${check ? 'Verified' : 'Generated'} ${manifest.count} standalone icons.`);
