#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readComponentDocEntries, rootDir } from './read-component-docs.mjs';

const entries = readComponentDocEntries();
const docs = entries.map((entry) => entry.doc);
const check = process.argv.includes('--check');
const manifestPath = join(rootDir, 'component-manifest.json');
const llmsPath = join(rootDir, 'llms.txt');
const registryPath = join(rootDir, 'src/docs/component-docs.ts');
const currentManifest = check ? readFileSync(manifestPath, 'utf8') : undefined;
const generatedAt = currentManifest
  ? JSON.parse(currentManifest).generatedAt
  : new Date().toISOString();

const manifest = {
  schemaVersion: 1,
  packageName: '@rockshin/tao-ui',
  generatedAt,
  components: docs,
};

function categoryGroups() {
  const groups = new Map();

  for (const doc of docs) {
    const entries = groups.get(doc.category) ?? [];
    entries.push(doc.displayName);
    groups.set(doc.category, entries);
  }

  return [...groups.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function renderLlmsTxt() {
  const lines = [
    '# @rockshin/tao-ui',
    '',
    '> A component library for React 18.2 and 19 with semantic DOM customization and OKLCH-based theming.',
    '',
    '## Install',
    '',
    '```bash',
    'npm install @rockshin/tao-ui',
    '```',
    '',
    'Peer dependencies: `react ^18.2.0 || ^19.0.0`, `react-dom ^18.2.0 || ^19.0.0`. Minimum version: React and React DOM 18.2; React 19 is also supported.',
    '`dayjs` is a regular dependency and is installed automatically.',
    'Import components from subpaths such as `@rockshin/tao-ui/button` and `TaoProvider` from `@rockshin/tao-ui/provider` to load only their component dependencies and shared theme styles. No separate CSS import is needed.',
    'The package root remains available and includes all component styles.',
    '',
    '## Core Concepts',
    '',
    '- `TaoProvider` supplies size, disabled, variant, portal scope, and theme seed token defaults.',
    '- Components expose semantic DOM customization through `classNames` and `styles` props.',
    '- Theme tokens are CSS custom properties prefixed with `--tao-*`; import `tokenVar(name)` and `taoTokenNames` from `@rockshin/tao-ui/tokens`.',
    '- Import `componentDocs` and `getComponentDoc(name)` from `@rockshin/tao-ui/meta` for machine-readable component metadata.',
    '- Resolve `@rockshin/tao-ui/component-manifest.json` for plain JSON without loading component code.',
    '- [Agent guide](https://rickyshin93.github.io/tao-ui/guide/agents.md): read contracts, choose imports, and verify generated code.',
    '- [Website discovery index](https://rickyshin93.github.io/tao-ui/agent-manifest.json): current website version and bilingual Markdown/API links. Match it to your installed version.',
    '',
    '## Component Groups',
    '',
  ];

  for (const [category, names] of categoryGroups()) {
    lines.push(`- ${category}: ${names.join(', ')}`);
  }

  lines.push('', '## Components', '');

  for (const doc of docs) {
    lines.push(
      `### ${doc.displayName}`,
      '',
      doc.description,
      '',
      `- Category: ${doc.category}`,
      `- Exports: ${doc.exports.map((name) => `\`${name}\``).join(', ')}`,
      `- Source: \`${doc.source}\``,
    );

    if (doc.story) {
      lines.push(`- Storybook: \`${doc.story}\``);
    }

    if (doc.tests.length > 0) {
      lines.push(
        `- Tests: ${doc.tests.map((testPath) => `\`${testPath}\``).join(', ')}`,
      );
    }

    if (doc.semanticParts?.length) {
      lines.push(
        `- Semantic parts: ${doc.semanticParts.map((part) => `\`${part}\``).join(', ')}`,
      );
    }

    lines.push('', doc.usage.description, '');
  }

  lines.push(
    '## Notes For Code Generation',
    '',
    '- Prefer component subpaths for smaller imports; the root entry remains supported.',
    '- Customize internals through semantic `classNames` and `styles`, not private class names.',
    '- Prefer provider-level defaults for app-wide size, disabled, variant, and theme choices.',
    '- Use `Modal.useModal()` inside React components so dialogs inherit the surrounding provider context.',
    '',
  );

  return `${lines.join('\n').trim()}\n`;
}

function renderComponentDocsModule() {
  const imports = entries.map(
    ({ fileName, exportName }) =>
      `import { ${exportName} } from './components/${fileName.replace(/\.ts$/, '')}';`,
  );
  const values = entries.map(({ exportName }) => `  ${exportName},`);

  return `${[
    '// Generated by scripts/generate-component-manifest.mjs. Do not edit by hand.',
    "import type { ComponentDoc } from './component-doc';",
    ...imports,
    '',
    'export const componentDocs = [',
    ...values,
    '] satisfies ComponentDoc[];',
    '',
    'export function getComponentDoc(name: string): ComponentDoc | undefined {',
    '  const normalizedName = name.toLowerCase();',
    '',
    '  return componentDocs.find((doc) => {',
    '    if (doc.name.toLowerCase() === normalizedName) return true;',
    '    return doc.exports.some(',
    '      (exportName) => exportName.toLowerCase() === normalizedName,',
    '    );',
    '  });',
    '}',
    '',
  ].join('\n')}`;
}

const nextManifest = `${JSON.stringify(manifest, null, 2)}\n`;
const nextLlms = renderLlmsTxt();
const nextRegistry = renderComponentDocsModule();

if (check) {
  const stale = [];
  if (currentManifest !== nextManifest) stale.push('component-manifest.json');
  if (readFileSync(llmsPath, 'utf8') !== nextLlms) stale.push('llms.txt');
  if (readFileSync(registryPath, 'utf8') !== nextRegistry) {
    stale.push('src/docs/component-docs.ts');
  }
  if (stale.length > 0) {
    console.error(
      `Generated docs are stale: ${stale.join(', ')}. Run bun run docs:generate.`,
    );
    process.exit(1);
  }

  console.log(`Checked generated docs for ${docs.length} components.`);
  process.exit(0);
}

writeFileSync(manifestPath, nextManifest);
writeFileSync(llmsPath, nextLlms);
writeFileSync(registryPath, nextRegistry);

console.log(
  `Generated component-manifest.json and llms.txt from ${docs.length} component docs.`,
);
